"""Single-workspace bearer credentials with server-side resource permissions."""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import hmac
import json
from pathlib import Path
import re


@dataclass(frozen=True)
class Principal:
    subject: str
    role: str


class ConsoleCredentials:
    """File contains SHA-256 token digests, never provider/API plaintext keys.

    Tokens must have at least 256 bits of random entropy, generated by the setup tool.
    Each database is one workspace; a grant never spans other database instances.
    """
    def __init__(self, entries: list[dict]):
        if not isinstance(entries, list) or not 1 <= len(entries) <= 100:
            raise ValueError("Credentials require 1 to 100 principals")
        self.entries = []
        seen = set()
        for row in entries:
            if not isinstance(row, dict) or set(row) != {"subject", "role", "token_sha256"}:
                raise ValueError("Invalid credentials record")
            subject, role, digest = row["subject"], row["role"], row["token_sha256"]
            if not isinstance(subject, str) or not re.fullmatch(r"[a-zA-Z0-9_.-]{1,64}", subject):
                raise ValueError("Invalid principal subject")
            if not isinstance(role, str) or role not in {"viewer", "operator", "admin"} or subject in seen:
                raise ValueError("Invalid principal role or duplicate subject")
            if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
                raise ValueError("Invalid credential digest")
            if any(item[0] == digest for item in self.entries):
                raise ValueError("Duplicate credential digest")
            self.entries.append((digest, Principal(subject, role)))
            seen.add(subject)

    @classmethod
    def load(cls, path: str | Path):
        with Path(path).open("rb") as stream:
            raw = stream.read(65537)
        if len(raw) > 65536:
            raise ValueError("Credential file too large")
        return cls(json.loads(raw))

    def authenticate(self, header: str | None) -> Principal | None:
        if not header or not header.startswith("Bearer ") or not 32 <= len(header[7:]) <= 256:
            return None
        digest = hashlib.sha256(header[7:].encode()).hexdigest()
        result = None
        for expected, principal in self.entries:
            if hmac.compare_digest(expected, digest):
                result = principal
        return result

    @staticmethod
    def permitted(principal: Principal, method: str, path: str) -> bool:
        if principal.role == "admin":
            return True
        if path.startswith(("/api/v1/audit", "/api/v1/billing")):
            return False
        if method in {"GET", "HEAD"}:
            return path.startswith(("/api/v1/", "/openapi.json"))
        return principal.role == "operator" and path in {"/api/v1/policies/validate", "/api/v1/demo/runs"}
