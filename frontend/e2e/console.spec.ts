test('bearer login UI keeps token in memory and restricts viewer navigation', async ({ page }) => {
  const token = 'browser-test-token-only-1234567890'
  await page.route('**/api/v1/health', async route => {
    const response = await route.fetch()
    await route.fulfill({ json: { ...await response.json(), authentication: 'bearer' } })
  })
  await page.route('**/api/v1/session', async route => {
    if (route.request().headers()['authorization'] === `Bearer ${token}`) await route.fulfill({ json: { subject: 'reader', role: 'viewer' } })
    else await route.fulfill({ status: 401, json: { error: { message: 'Invalid token' } } })
  })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '连接工作空间' })).toBeVisible()
  await page.getByLabel('工作空间访问凭证').fill('incorrect-token')
  await page.getByRole('button', { name: '连接', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('凭证无效')
  await page.getByLabel('工作空间访问凭证').fill(token)
  await page.getByRole('button', { name: '连接', exact: true }).click()
  await expect(page.getByRole('heading', { name: '连接工作空间' })).not.toBeVisible()
  await expect(page.getByRole('link', { name: '成本账本' })).not.toBeVisible()
  await page.getByRole('link', { name: '防护策略', exact: true }).click()
  await expect(page.getByText('当前角色仅可查看策略。发布配置需要管理员权限。')).toBeVisible()
  await expect(page.getByRole('button', { name: '保存策略' })).toBeDisabled()
  expect(await page.evaluate(() => JSON.stringify([Object.values(localStorage), Object.values(sessionStorage)]))).not.toContain(token)
  await page.reload()
  await expect(page.getByRole('heading', { name: '连接工作空间' })).toBeVisible()
})

