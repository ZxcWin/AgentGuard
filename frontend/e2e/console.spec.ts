test('policy validation, version update and conflict handling', async ({ page, request }) => {
  await page.goto('/#/policies')
  const input = page.getByLabel('每次运行 Token 上限', { exact: false })
  await expect(input).toBeVisible()
  const policy = await (await request.get('/api/v1/policies/current')).json()
  await input.fill(String(Number(policy.config.token.run_token_budget) + 100))
  await page.getByRole('button', { name: '校验配置' }).click()
  await expect(page.getByText('校验通过，可以保存当前配置。')).toBeVisible()
  await page.getByRole('button', { name: '保存策略' }).click()
  await expect(page.locator('.version-tag')).toContainText('v' + (policy.version + 1))
  await expect(page.getByText('策略已保存。新 Run 将使用新版本，已有 Run 保持原快照。')).toBeVisible()
  const updated = await (await request.get('/api/v1/policies/current')).json()
  await request.put('/api/v1/policies/current', { data: { expected_version: updated.version, config: { token: { run_token_budget: 32000 } } } })
  await input.fill('32500')
  await page.getByRole('button', { name: '保存策略' }).click()
  await expect(page.getByText('策略版本已被其他操作更新。请重新加载最新策略后编辑。')).toBeVisible()
  await page.getByRole('button', { name: '加载最新版本' }).click()
  await expect(input).toHaveValue('32000')
})

test('disconnection has a retry state and never substitutes demo metrics', async ({ page }) => {
  await page.route('**/api/v1/overview?*', route => route.fulfill({ status: 503, json: { error: { message: 'Service unavailable' } } }))
  await page.goto('/')
  await expect(page.getByText('暂时无法加载')).toBeVisible()
  await expect(page.locator('.metric-card')).toHaveCount(0)
  await page.unroute('**/api/v1/overview?*')
  await page.getByRole('button', { name: '重新加载' }).click()
  await expect(page.locator('.metric-card')).toHaveCount(4)
})

