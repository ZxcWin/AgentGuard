test('tool safety policies validate arrays and persist approval and idempotency requirements', async ({ page, request }) => {
  await page.goto('/#/policies')
  const keys = page.getByLabel('必须带幂等键的工具 JSON', { exact: true })
  const approvals = page.getByLabel('必须审批的工具 JSON', { exact: true })
  await keys.fill('{}')
  await page.getByRole('button', { name: '校验配置' }).click()
  await expect(page.getByRole('status')).toContainText('idempotency_required_for 必须是 JSON 数组。')
  await keys.fill('["send"]')
  await approvals.fill('["send", "send"]')
  await page.getByRole('button', { name: '校验配置' }).click()
  await expect(page.getByRole('status')).toContainText('不能包含重复工具名')
  await approvals.fill('["send"]')
  await page.getByLabel('审批等待上限', { exact: false }).fill('5')
  await page.getByRole('button', { name: '保存策略' }).click()
  await expect(page.getByText('策略已保存。新 Run 将使用新版本，已有 Run 保持原快照。')).toBeVisible()
  const policy = await (await request.get('/api/v1/policies/current')).json()
  expect(policy.config.tools.idempotency_required_for).toEqual(['send'])
  expect(policy.config.tools.approval_required_for).toEqual(['send'])
  expect(policy.config.tools.approval_timeout_seconds).toBe(5)
  await page.reload()
  await expect(keys).toHaveValue('[\n  "send"\n]')
  await expect(approvals).toHaveValue('[\n  "send"\n]')
  await expect(page.getByLabel('审批等待上限', { exact: false })).toHaveValue('5')
})
