def styled_body(lines: list[str], size: int, color: str) -> str:
    paragraphs = []
    for index, line in enumerate(lines):
        if color == "FFFFFF":
            line_color = "FFFFFF"
        elif color == NAVY:
            line_color = NAVY
        elif index == 0:
            line_color = RED
        else:
            line_color = NAVY
        bold = "<a:b/>" if index == 0 else ""
        paragraphs.append(
            f'<a:p><a:pPr marL="0" indent="0"/><a:r><a:rPr lang="zh-CN" sz="{size}">{bold}'
            f'<a:solidFill><a:srgbClr val="{line_color}"/></a:solidFill>'
            f'<a:latin typeface="Arial"/><a:ea typeface="SimSun"/></a:rPr>'
            f'<a:t>{esc(line)}</a:t></a:r><a:endParaRPr lang="zh-CN"/></a:p>'
        )
    return "".join(paragraphs)


