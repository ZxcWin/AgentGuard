def dashed_rule(shape_id: int, x: int, y: int, h: int) -> str:
    pieces = []
    current = y
    piece_height = 90000
    gap = 65000
    while current < y + h:
        pieces.append(short_line(shape_id, x, current, 18000, min(piece_height, y + h - current), CYAN))
        current += piece_height + gap
        shape_id += 1
    return "".join(pieces)


