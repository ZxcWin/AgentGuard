def reference_slide_xml(title: str, subtitle: str, blocks: list[tuple[int, int, int, int, list[str], int, str, bool, str | None]], number: int) -> str:
    title_size = 1950 if len(title) > 17 else 2250
    shapes = [
        styled_text(2, 550000, 180000, 4800000, 600000, [section_label(number)], 2400, RED),
        styled_text(3, 5650000, 180000, 6100000, 600000, [title], title_size, NAVY),
        short_line(4, 550000, 1000000, 11200000, 32000, PINK),
        short_line(5, 550000, 1000000, 5000000, 18000, RED),
    ]
    if subtitle:
        shapes.append(styled_text(6, 800000, 1170000, 10600000, 450000, [subtitle], 1600, NAVY))
    sid = 20
    block_positions = []
    for x, y, w, h, lines, size, color, bold_first, fill in blocks:
        shifted_y = y + 260000
        if fill:
            shapes.append(styled_box(sid, x - 70000, shifted_y - 55000, w + 140000, h + 80000, fill))
            sid += 1
        text_color = "FFFFFF" if color == "FFFFFF" else "CONTENT"
        shapes.append(styled_text(sid, x, shifted_y, w, h, lines, size, text_color))
        sid += 1
        block_positions.append((x, w, shifted_y, h))
    column_starts = sorted({x for x, w, y, h in block_positions if x < 9000000})
    if len(column_starts) in {2, 3} and number not in {2, 11}:
        for index in range(1, len(column_starts)):
            boundary = column_starts[index] - 180000
            shapes.append(dashed_rule(sid, boundary, 2050000, 2850000))
            sid += 30
    shapes.append(styled_text(99, 10900000, 6400000, 650000, 250000, [f"{number:02d}"], 1050, RED))
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:a="{NS_A}" xmlns:r="{NS_R}" xmlns:p="{NS_P}"><p:cSld><p:spTree>
<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
{''.join(shapes)}</p:spTree></p:cSld><p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr></p:sld>'''


